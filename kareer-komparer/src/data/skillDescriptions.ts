/**
 * Helper to get a description for any given skill.
 * Normalizes input keys to ensure case and spacing mismatches resolve correctly.
 */
export const getSkillDescription = (skill: string): string => {
  const normalizedKey = skill.toLowerCase().trim();
  
  if (skillDescriptions[normalizedKey]) {
    return skillDescriptions[normalizedKey];
  }
  
  // Fuzzy lookup if exact match fails
  for (const [key, value] of Object.entries(skillDescriptions)) {
    if (normalizedKey.includes(key) || key.includes(normalizedKey)) {
      return value;
    }
  }
  
  return "Practical knowledge and execution of this skill within this career pathway.";
};
